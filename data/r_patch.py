import r_world3

def set_broth(rid, new='Мясной бульон', note=None, where=None):
    r = find(rid)
    lists = [r['ing']] + [v.get('ing', []) for v in r.get('variants', []) if where is None or v['name'] == where]
    for L in lists:
        for i in L:
            if i[0] == 'Куриный бульон':
                i[0] = new
                if len(i) < 4: i.append({})
                i[3]['note'] = note or 'или куриный — со склада возьмётся любой'

